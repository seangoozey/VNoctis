"""Preserve known native engine defaults in a temporary web build overlay."""

import ast
import io
import os
import re
import shutil
import tokenize
from pathlib import Path


_SHIM_NAME = "_vnm_legacy_search_prefixes.rpy"
_SHIM = '''# Generated by VNoctis for engines with the legacy images/ fallback.
# Run before ordinary game init, allowing game settings to override this default.
init -999 python:
    if config.search_prefixes == [""]:
        config.search_prefixes = ["", "images/"]
'''


def needs_legacy_image_lookup(game_path: str) -> bool:
    """Read a literal engine default without executing imported Python code.

    Older engines may contain Python 2 syntax, so parsing the entire module
    with Python 3 is unsuitable. Unknown or dynamic defaults are left alone.
    """
    config = Path(game_path) / "renpy" / "config.py"
    if not config.is_file():
        return False
    match = re.search(
        r"^search_prefixes\s*=\s*(\[[^\]]*\])[^\S\n]*(?:#[^\n]*)?$",
        config.read_text(encoding="utf-8", errors="replace"),
        re.MULTILINE,
    )
    if not match:
        return False
    try:
        return ast.literal_eval(match.group(1)) == ["", "images/"]
    except (ValueError, SyntaxError):
        return False


def create_uncompressed_overlay(game_path: str, overlay_path: str) -> None:
    """Link assets into a disposable build tree, including real directories."""
    source = Path(game_path).resolve()
    overlay = Path(overlay_path)
    if overlay.exists():
        shutil.rmtree(overlay)
    for root, _, files in os.walk(source):
        destination = overlay / Path(root).relative_to(source)
        destination.mkdir(parents=True, exist_ok=True)
        for name in files:
            (destination / name).symlink_to(Path(root) / name)


def prepare_build_overlay(overlay_path: str, legacy_image_lookup: bool) -> None:
    """Keep compiler outputs/settings local and optionally install the shim."""
    overlay = Path(overlay_path)
    # The SDK can recompile scripts. Do not let its writes follow links back
    # into the imported game, with or without asset compression enabled.
    for root, _, files in os.walk(overlay):
        for name in files:
            path = Path(root) / name
            if path.is_symlink() and (
                path.suffix.lower() in {".rpy", ".rpyc", ".rpym", ".rpymc"}
                or path == overlay / "progressive_download.txt"
            ):
                source = path.resolve()
                path.unlink()
                shutil.copy2(source, path)
    if legacy_image_lookup:
        shim = overlay / "game" / _SHIM_NAME
        if shim.exists() or shim.with_suffix(".rpyc").exists():
            raise RuntimeError(f"Reserved compatibility script already exists: {shim.name}")
        shim.parent.mkdir(parents=True, exist_ok=True)
        shim.write_text(_SHIM, encoding="utf-8")


def adapt_legacy_urlopen_imports(overlay_path: str, sdk_version: str) -> list[str]:
    """Translate only standalone urllib2.urlopen imports in owned game scripts.

    Token inspection avoids changing dialogue, comments or multiline strings.
    This does not emulate networking or rewrite other Python 2 interfaces.
    """
    major = sdk_version.split(".", 1)[0]
    if not major.isdigit() or int(major) < 8:
        return []
    overlay = Path(overlay_path)
    changed = []
    for path in sorted((overlay / "game").rglob("*.rpy")):
        raw = path.read_bytes()
        try:
            source = raw.decode("utf-8-sig")
            tokens = list(tokenize.generate_tokens(io.StringIO(source).readline))
        except (UnicodeError, tokenize.TokenError, IndentationError, SyntaxError):
            continue
        lines = source.splitlines(keepends=True)
        replacements = []
        for index in range(len(tokens) - 4):
            group = tokens[index:index + 4]
            if ([t.type for t in group] != [tokenize.NAME] * 4
                    or [t.string for t in group] != ["from", "urllib2", "import", "urlopen"]):
                continue
            first, module, _, last = group
            if first.start[0] != last.end[0]:
                continue
            line = lines[first.start[0] - 1]
            if line[:first.start[1]].strip():
                continue
            if tokens[index + 4].type not in (tokenize.COMMENT, tokenize.NEWLINE):
                continue
            replacements.append(module)
        if not replacements:
            continue
        for token in reversed(replacements):
            row = token.start[0] - 1
            lines[row] = lines[row][:token.start[1]] + "urllib.request" + lines[row][token.end[1]:]
        # Detach links even when called independently of overlay preparation.
        if path.is_symlink():
            path.unlink()
        encoding = "utf-8-sig" if raw.startswith(b"\xef\xbb\xbf") else "utf-8"
        path.write_bytes("".join(lines).encode(encoding))
        # Force recompilation; archived bytecode may otherwise take precedence.
        path.with_suffix(".rpyc").unlink(missing_ok=True)
        changed.append(path.relative_to(overlay).as_posix())
    return changed
